// प्रश्नों को स्क्रीन पर दिखाना
function loadQuestions(questions) {
    questionsContainer.innerHTML = '';
    questions.forEach((q) => {
        const card = document.createElement('div');
        card.className = 'question-card';

        const tagHTML = q.tag ? `<span class="q-exam-tag">(${q.tag})</span>` : '';

        // विकल्प तैयार करना
        let optionsHTML = '';
        for (const [key, val] of Object.entries(q.options)) {
            optionsHTML += `<div class="option-box"><strong>(${key})</strong> ${val}</div>`;
        }

        card.innerHTML = `
            <div class="q-title">${q.id}. ${q.question} ${tagHTML}</div>
            <div class="options-grid">
                ${optionsHTML}
            </div>
            <button class="toggle-ans-btn" onclick="toggleAnswer(${q.id})">उत्तर देखें</button>
            <div class="answer-box" id="ans-${q.id}">
                सही उत्तर: ${q.answer}
            </div>
        `;
        questionsContainer.appendChild(card);
    });
}

// उत्तर शो / हाइड टॉगल फ़ंक्शन
window.toggleAnswer = function(id) {
    const box = document.getElementById(`ans-${id}`);
    const btn = box.previousElementSibling;
    if (box.classList.contains('show')) {
        box.classList.remove('show');
        btn.textContent = 'उत्तर देखें';
    } else {
        box.classList.add('show');
        btn.textContent = 'उत्तर छुपाएं';
    }
};

// साइडबार अध्याय क्लिक इवेंट
document.querySelectorAll('.chapter-item').forEach(item => {
    item.addEventListener('click', function() {
        document.querySelectorAll('.chapter-item').forEach(i => i.classList.remove('active'));
        this.classList.add('active');
        
        const chId = this.getAttribute('data-chapter');
        currentChapterTitle.textContent = this.textContent;
        
        if (chId === "1") {
            loadQuestions(chapter1Questions);
            totalQuestionsCount.textContent = `कुल प्रश्न: ${chapter1Questions.length}`;
        } else {
            questionsContainer.innerHTML = `<p style="padding: 20px; text-align: center; color: #888;">इस अध्याय के प्रश्न जल्द ही जोड़े जाएंगे।</p>`;
            totalQuestionsCount.textContent = `कुल प्रश्न: 0`;
        }
        
        closeMenu();
    });
});

